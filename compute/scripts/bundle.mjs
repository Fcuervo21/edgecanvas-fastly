// Bundles the hosted frontend (dist-hosted/) and the TypeScript edge app into build/index.js,
// which js-compute-runtime compiles to bin/main.wasm. Private data never enters the bundle.
import { build } from 'esbuild';
import { readdirSync, readFileSync, mkdirSync, writeFileSync, statSync } from 'node:fs';
import { extname, join, relative, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..'), site = resolve(root, '../dist-hosted');
const types = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml', '.png': 'image/png', '.ico': 'image/x-icon', '.woff2': 'font/woff2', '.json': 'application/json' };
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) { walk(path); continue; }
    const ext = extname(name).toLowerCase();
    if (!types[ext]) throw new Error(`Refusing to bundle unexpected file type: ${name}`);
    const body = readFileSync(path);
    if (/StepsData|\.csv\b/i.test(name)) throw new Error(`Refusing to bundle private data: ${name}`);
    files.push({ path: '/' + relative(site, path).replaceAll('\\', '/'), type: types[ext], body: body.toString('base64') });
  }
})(site);
if (!files.some(f => f.path === '/index.html')) throw new Error('Run `npm run build:hosted` first.');
mkdirSync(resolve(root, 'build'), { recursive: true });
writeFileSync(resolve(root, 'build/assets.js'), `// Generated by scripts/bundle.mjs from dist-hosted/. Do not edit.
const files = ${JSON.stringify(Object.fromEntries(files.map(f => [f.path, { type: f.type, body: f.body }])))};
const decoded = new Map();
export function assets(path) {
  const key = files[path] ? path : (path.startsWith('/assets/') ? path : '/index.html');
  const file = files[key];
  if (!file) return null;
  if (!decoded.has(key)) decoded.set(key, Uint8Array.from(atob(file.body), c => c.charCodeAt(0)));
  const immutable = key.startsWith('/assets/');
  return new Response(decoded.get(key), { headers: { 'content-type': file.type,
    'cache-control': immutable ? 'public, max-age=31536000, immutable' : 'no-cache',
    'x-content-type-options': 'nosniff', 'referrer-policy': 'no-referrer', 'x-frame-options': 'DENY',
    'strict-transport-security': 'max-age=31536000', 'permissions-policy': 'camera=(), microphone=(), geolocation=()',
    'content-security-policy': "default-src 'self'; img-src 'self' data:; style-src 'self' 'unsafe-inline'; base-uri 'none'; form-action 'self'; frame-ancestors 'none'" } });
}
`);
writeFileSync(resolve(root, 'build/assets.d.ts'), 'export function assets(path: string): Response | null;\n');
await build({ entryPoints: [resolve(root, 'src/main.ts')], bundle: true, format: 'esm', target: 'es2022',
  outfile: resolve(root, 'build/index.js'), external: ['fastly:*'], logLevel: 'warning' });
console.log(`Bundled ${files.length} frontend files and the edge app into build/index.js`);
